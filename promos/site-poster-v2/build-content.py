"""Picks stories from the live site's data (gh-pages data.json + img/) for the promo stills.

    python3 promos/site-poster-v2/build-content.py <gh-pages checkout> [story ids...]

Writes promos/site-poster-v2/content.js (titles, country, photo) and copies the photos to img/ (1400 px max).
Without ids it takes the latest stories that have a photo, one per country where it can.
"""
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1]
WANT = sys.argv[2:]
NAMES = {"mr": "موريتانيا", "ma": "المغرب", "dz": "الجزائر", "tn": "تونس", "ly": "ليبيا", "eh": "الصحراء",
         "az": "أزواد", "sn": "السنغال", "ml": "مالي", "ne": "النيجر", "td": "تشاد", "gm": "غامبيا"}

data = json.load(open(os.path.join(SRC, "data.json"), encoding="utf-8"))
arts = {a["id"]: a for a in data["articles"]}
has_photo = lambda a: a.get("images") and os.path.exists(os.path.join(SRC, a["images"][0]))
if WANT:
    picked = [arts[i] for i in WANT]
else:
    picked, seen = [], set()
    for a in data["articles"]:
        if has_photo(a) and (a.get("portals") or ["?"])[0] not in seen:
            picked.append(a)
            seen.add((a.get("portals") or ["?"])[0])
        if len(picked) == 8:
            break

os.makedirs(os.path.join(HERE, "img"), exist_ok=True)
out = []
for a in picked:
    im = Image.open(os.path.join(SRC, a["images"][0])).convert("RGB")
    im.thumbnail((1400, 1400))
    name = f"img/{a['id']}.jpg"
    im.save(os.path.join(HERE, name), quality=88)
    ports = a.get("portals") or []
    # the label: the opinion section by name, else the story's first country
    label = a.get("category") if a.get("category") == "الرأي الحر" else NAMES.get(ports[0], "") if ports else ""
    out.append({"id": a["id"], "title": a["title"].strip(), "label": label, "photo": name, "date": a.get("createdAt")})
    print(a["id"], label, a["title"][:60])

with open(os.path.join(HERE, "content.js"), "w", encoding="utf-8") as fh:
    fh.write("// Generated by build-content.py from the site's data.json. Stories shown on the promo stills.\n")
    fh.write("window.STORIES = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
