// Map for an infographic's `map` scene: country outlines (Natural Earth, world-atlas 50m) projected in Mercator
// to fit the chosen countries in the scene's map box. Western Sahara is kept as its own territory (repo default).
//   node tools/make-infographic-map.js <graphic folder> mr=478 dz=012 ma=504 tn=788 ly=434
// Writes graphics/<folder>/map.js: window.MAP = { w, h, main: {code: path}, other: [path], ws: path, at: {code: [x, y]} }
const fs = require('fs');
const path = require('path');
const d3 = require('d3-geo');
const topojson = require('topojson-client');
const world = require('world-atlas/countries-50m.json');

const [folder, ...pairs] = process.argv.slice(2);
const W = 968, H = 500;  // map box inside the 1080x1350 design (x 56..1024)
const codes = Object.fromEntries(pairs.map(p => p.split('=')));
const feats = topojson.feature(world, world.objects.countries).features;
const main = Object.entries(codes).map(([c, id]) => [c, feats.find(f => f.id === id)]);
const proj = d3.geoMercator().fitExtent([[10, 10], [W - 10, H - 10]], { type: 'FeatureCollection', features: main.map(m => m[1]) });
const gp = d3.geoPath(proj);
const r = d => d.replace(/(\d+\.\d)\d+/g, '$1');
const out = { w: W, h: H, main: {}, other: [], ws: '', at: {} };
for (const [c, f] of main) {
  out.main[c] = r(gp(f));
  // label point: centroid of the largest polygon
  const polys = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates.map(p => ({ type: 'Polygon', coordinates: p })) : [f.geometry];
  const big = polys.sort((a, b) => d3.geoArea(b) - d3.geoArea(a))[0];
  out.at[c] = gp.centroid(big).map(v => Math.round(v));
}
const ids = new Set(Object.values(codes));
for (const f of feats) {
  if (ids.has(f.id)) continue;
  const b = gp.bounds(f);
  if (!isFinite(b[0][0]) || b[1][0] < -50 || b[0][0] > W + 50 || b[1][1] < -50 || b[0][1] > H + 50) continue;
  const d = d3.geoBounds(f);
  if (d[0][0] > d[1][0]) continue;  // antimeridian
  if (f.id === '732') out.ws = r(gp(f)); else out.other.push(r(gp(f)));
}
const file = path.join(__dirname, '..', 'graphics', folder, 'map.js');
fs.writeFileSync(file, '// Generated by tools/make-infographic-map.js. Do not edit.\nwindow.MAP = ' + JSON.stringify(out) + ';\n');
console.log('wrote', path.relative(process.cwd(), file), Math.round(fs.statSync(file).size / 1024) + ' KB', out.at);
