// Bundles the geo libraries and Natural Earth countries (world-atlas 50m) for the infographic's map scenes
// (globe, geo): src/vendor-geo.js = d3-array + d3-geo + topojson-client + window.WORLD. Re-run after npm updates.
const fs = require('fs');
const path = require('path');
const nm = p => fs.readFileSync(path.join(__dirname, '..', 'node_modules', p), 'utf8');
const out = [nm('d3-array/dist/d3-array.min.js'), nm('d3-geo/dist/d3-geo.min.js'), nm('topojson-client/dist/topojson-client.min.js'),
  'window.WORLD = ' + JSON.stringify(JSON.parse(nm('world-atlas/countries-50m.json'))) + ';'].join('\n');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'vendor-geo.js'), '// Generated by tools/make-geo-vendor.js. Do not edit.\n' + out);
console.log('src/vendor-geo.js', Math.round(out.length / 1024) + ' KB');
